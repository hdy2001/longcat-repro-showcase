// 邻接表
export const GRAPH: Map<string, string[]> = (() => {
  const g = new Map<string, string[]>();
  for (const w of WAYPOINTS) g.set(w.id, []);
  for (const [a, b] of EDGES) { g.get(a)!.push(b); g.get(b)!.push(a); }
  return g;
})();

export const WAYPOINT_MAP: Map<string, Waypoint> = new Map(WAYPOINTS.map(w => [w.id, w]));

// BFS 最短路
export function findPath(from: string, to: string): string[] {
  if (from === to) return [from];
  const prev = new Map<string, string | null>([[from, null]]);
  const q: string[] = [from];
  while (q.length) {
    const cur = q.shift()!;
    for (const nb of GRAPH.get(cur) ?? []) {
      if (!prev.has(nb)) {
        prev.set(nb, cur);
        if (nb === to) {
          const path = [to];
          let p = to;
          while (prev.get(p)) { p = prev.get(p)!; path.unshift(p); }
          return path;
        }
        q.push(nb);
      }
    }
  }
  return [from];
}

