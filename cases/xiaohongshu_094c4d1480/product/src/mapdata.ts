  w: number; d: number;
  h: number; y0?: number;
  kind: 'wall' | 'roof' | 'crate' | 'sandbag' | 'barrel' | 'step' | 'platform' | 'prop';
  rotY?: number; // 绕 y 轴旋转(弧度), 仅用于装饰
